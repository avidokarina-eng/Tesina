import streamlit as st
import numpy as np
import plotly.graph_objects as go
import pandas as pd

st.set_page_config(page_title="Tesina - Limite de una funcion", layout="wide")
st.sidebar.title("Tesina")
unidad = st.sidebar.radio("Elegi la unidad:", ["Unidad 0 - Introduccion", "Unidad 1 - Limite de una funcion"])

if unidad == "Unidad 0 - Introduccion":
    st.title("Unidad 0 - Introduccion al Limite")
    st.write("**¿Que es un limite?** Es la idea mas importante del calculo. Nos pregunta: ¿a que valor se acerca una funcion cuando x se acerca a un numero, sin llegar a ser ese numero?")
    st.info("Ejemplo de la vida real: Si te acercas cada vez mas a la puerta sin tocarla, el limite es la puerta. No importa si la tocas o no, importa a donde te acercas.")
    st.write("En esta unidad vamos a adivinar el limite usando una tabla y un grafico, antes de aprender la definicion formal en la Unidad 1.")
    st.header("El problema que inicia todo")
    st.write("Queremos saber que pasa con esta funcion cuando x se acerca a 0:")
    st.latex(r"f(x) = \frac{\sin x}{x}")
    st.write("**Problema:** Si ponemos x = 0, nos queda 0/0, que no se puede calcular. Entonces, ¿que hacemos? Probamos con valores cada vez mas cerca de 0, sin ser 0.")
    st.subheader("Tabla de valores - acercandonos a 0")
    st.table(pd.DataFrame({
        "x por izquierda": [-1.0, -0.5, -0.1, -0.01, -0.001],
        "f(x)": [0.84147, 0.95885, 0.99833, 0.99998, 1.00000],
        "x por derecha": [1.0, 0.5, 0.1, 0.01, 0.001],
        "f(x) ": [0.84147, 0.95885, 0.99833, 0.99998, 1.00000]
}))
    st.success("¿Que ves? Por izquierda y por derecha, f(x) se acerca cada vez mas a 1. Entonces intuimos que el limite es 1.")
    st.write("Abajo podes mover el punto rojo con el slider y comprobarlo vos misma:")
    st.title("Visualizador del Limite")
    st.latex(r"\lim_{x \to 0} \frac{\sin x}{x} = 1")
    x = st.slider("Mover x hacia 0", -3.0, 3.0, 1.5)
    def f(v):
        return 1.0 if abs(v) < 0.0001 else np.sin(v)/v
    xs = np.linspace(-3, 3, 500)
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=xs, y=[f(i) for i in xs], mode="lines", name="f(x) = sin(x)/x"))
    fig.add_trace(go.Scatter(x=[x], y=[f(x)], mode="markers", marker=dict(size=12, color="red"), name="Punto actual"))
    fig.add_hline(y=1, line_dash="dash")
    fig.update_layout(xaxis_title="x", yaxis_title="f(x)")
    st.plotly_chart(fig, use_container_width=True)
    st.metric("f(x)", f"{f(x):.5f}")
    if abs(x) > 1:
        st.warning("Acercate a 0...")
    else:
        st.success("Converge a 1")

elif unidad == "Unidad 1 - Limite de una funcion":
    st.title("Unidad 1 - Limite de una funcion")
    st.caption("Fuente: Stewart, James (1998). Calculo de una variable.")
    st.header("(1) DEFINICION - Limite")
    st.latex(r"\lim_{x \to a} f(x) = L")
    st.write("Se dice: el limite de f(x) es igual a L cuando x tiende a a si podemos acercar arbitrariamente los valores de f(x) a L (tanto como queramos) aproximando x a a, pero sin igualar a a.")
    st.info("Esto significa que los valores de f(x) se acercan mas y mas al numero L conforme x se aproxima al numero a (de ambos lados de a), pero x no es igual a a.")
    st.write("Notacion alternativa:")
    st.latex(r"f(x) \to L \quad \text{cuando} \quad x \to a")
    st.warning("Hay que subrayar la frase 'pero x no es igual a a'. En la busqueda del limite, nunca consideramos x = a. f(x) ni siquiera necesita estar definida cuando x = a. Lo unico que interesa es como se define f cerca de a.")
    st.subheader("Ejemplo de la Definicion (1)")
    st.write("Investiguemos la funcion:")
    st.latex(r"f(x) = x^2 - x + 2")
    st.write("cuando x se acerca a 2, pero sin ser igual a 2.")
    st.table(pd.DataFrame({
        "x por izquierda": [1.0, 1.5, 1.8, 1.9, 1.95, 1.99, 1.995, 1.999],
        "f(x) izquierda": [2.0, 2.75, 3.44, 3.71, 3.8525, 3.9701, 3.9850, 3.9970],
        "x por derecha": [3.0, 2.5, 2.2, 2.1, 2.05, 2.01, 2.005, 2.001],
        "f(x) derecha": [8.0, 5.75, 4.64, 4.31, 4.1525, 4.0301, 4.0150, 4.0030]
    }))
    st.latex(r"\lim_{x \to 2} (x^2 - x + 2) = 4")
    x1 = st.slider("Mover x hacia 2 - Ejemplo f(x)=x2-x+2", 0.0, 4.0, 1.5)
    def f1(v):
        return v**2 - v + 2
    xs = np.linspace(0, 4, 400)
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=xs, y=[f1(i) for i in xs], mode="lines", name="y = x2 - x + 2"))
    fig.add_trace(go.Scatter(x=[x1], y=[f1(x1)], mode="markers", marker=dict(size=13, color="red"), name="Punto actual"))
    fig
    st.header("(2) y (3) DEFINICION - Limites laterales")
    st.subheader("Limite por la izquierda")
    st.latex(r"\lim_{x \to a^{-}} f(x) = L")
    st.write("Se dice que el limite lateral izquierdo de f(x) cuando x tiende a a es igual a L si podemos acercar arbitrariamente los valores de f(x) a L por la izquierda, aproximando x a a, con x menor que a.")
    st.write("El simbolo x -> a- indica que solo se consideran valores de x menores que a.")
    st.subheader("Limite por la derecha")
    st.latex(r"\lim_{x \to a^{+}} f(x) = L")
    st.write("De igual forma, si precisamos que x sea mayor que a, obtenemos el limite lateral derecho.")
    st.write("El simbolo x -> a+ indica que solo se consideran valores de x mayores que a.")
    st.success("Regla clave (3): El limite existe si y solo si los dos laterales son iguales:")
    st.latex(r"\lim_{x \to a} f(x) = L \iff \lim_{x \to a^{-}} f(x) = L \quad y \quad \lim_{x \to a^{+}} f(x) = L")
    st.subheader("Ejemplo grafico - Limites laterales")
    st.latex(r"\lim_{x \to 0^{-}} H(x) = 0 \quad y \quad \lim_{x \to 0^{+}} H(x) = 1")
    st.write("En este ejemplo los laterales NO son iguales, entonces el limite general NO existe.")
    st.header("(4) DEFINICION - Limite infinito +infinito")
    st.latex(r"\lim_{x \to a} f(x) = \infty")
    st.write("Significa que los valores de f(x) se pueden incrementar arbitrariamente, tanto como queramos, acercando x lo suficiente a a (pero sin igualarla con a).")
    st.latex(r"f(x) \to \infty \quad \text{cuando} \quad x \to a")
    st.warning("El simbolo infinito NO es un numero. Solo expresa el modo particular en que NO existe el limite.")
    st.subheader("Ejemplo: 1/x2")
    st.latex(r"\lim_{x \to 0} \frac{1}{x^2} = \infty")
    x4 = st.slider("Mover x hacia 0 - Ejemplo 1/x2", -1.0, 1.0, 0.5)
    def f4(v):
        return 100 if abs(v) < 0.05 else 1/(v**2)
    xs4 = np.linspace(-1, 1, 500)
    fig4 = go.Figure()
    fig4.add_trace(go.Scatter(x=xs4, y=[min(f4(i), 50) for i in xs4], mode="lines", name="y = 1/x2"))
    fig4.add_trace(go.Scatter(x=[x4], y=[min(f4(x4), 50)], mode="markers", marker=dict(size=13, color="red"), name="Punto actual"))
    fig4.add_vline(x=0, line_dash="dash")
    fig4.update_layout(xaxis_title="x", yaxis_title="f(x)", yaxis_range=[0, 50])
    st.plotly_chart(fig4, use_container_width=True)
    st.metric("1/x2", f"{f4(x4):.2f}")
    st.caption("Figura 12 del libro: la curva sube sin limite en x = 0.")
    st.header("(5) DEFINICION - Limite infinito -infinito")
    st.latex(r"\lim_{x \to a} f(x) = -\infty")
    st.write("Quiere decir que los valores de f(x) se pueden volver arbitrariamente pequenos o grandes en valor absoluto pero negativos, acercando x lo suficiente a a (pero sin igualarlo con a).")
    st.latex(r"\lim_{x \to 0} \left( -\frac{1}{x^2} \right) = -\infty")
    st.caption("Figura 13 del libro: la curva baja sin limite en x = 0.")
    st.write("Definiciones para los limites unilaterales infinitos:")
    st.latex(r"\lim_{x \to a^{-}} f(x) = \infty \quad \quad \lim_{x \to a^{+}} f(x) = \infty")
    st.latex(r"\lim_{x \to a^{-}} f(x) = -\infty \quad \quad \lim_{x \to a^{+}} f(x) = -\infty")
    st.header("(6) DEFINICION - Asintota vertical")
    st.write("La recta x = a se llama asintota vertical de la curva y = f(x) si se cumple cuando menos una de las siguientes afirmaciones:")
    st.latex(r"\lim_{x \to a} f(x) = \infty \quad \lim_{x \to a^{-}} f(x) = \infty \quad \lim_{x \to a^{+}} f(x) = \infty")
    st.latex(r"\lim_{x \to a} f(x) = -\infty \quad \lim_{x \to a^{-}} f(x) = -\infty \quad \lim_{x \to a^{+}} f(x) = -\infty")
    st.write("Por ejemplo, el eje y es una asintota vertical de la curva y = 1/x2 porque se cumple el limite anterior.")
    st.subheader("EJEMPLO 9 - Determina los limites laterales")
    st.latex(r"\lim_{x \to 3^{+}} \frac{2}{x-3} \quad y \quad \lim_{x \to 3^{-}} \frac{2}{x-3}")
    st.write("Solucion: Si x se acerca a 3 y es mayor que 3, el denominador x - 3 es un numero positivo pequeno; entonces 2/(x-3) es un numero positivo grande.")
    st.latex(r"\lim_{x \to 3^{+}} \frac{2}{x-3} = \infty")
    st.write("De igual forma, si x se acerca a 3 pero es menor que 3, x - 3 es un numero negativo pequeno, y asi 2/(x-3) resulta un numero negativo grande.")
    st.latex(r"\lim_{x \to 3^{-}} \frac{2}{x-3} = -\infty")
    x9 = st.slider("Mover x hacia 3 - Ejemplo 2/(x-3)", 1.0, 5.0, 3.5)
    def f9(v):
        return 20 if abs(v-3) < 0.05 else 2/(v-3)
    xs9 = np.linspace(1, 5, 500)
    fig9 = go.Figure()
    fig9.add_trace(go.Scatter(x=xs9, y=[max(min(f9(i), 20), -20) for i in xs9], mode="lines", name="y = 2/(x-3)"))
    fig9.add_trace(go.Scatter(x=[x9], y=[max(min(f9(x9), 20), -20)], mode="markers", marker=dict(size=13, color="red"), name="Punto actual"))
    fig9.add_vline(x=3, line_dash="dash")
    fig9.update_layout(xaxis_title="x", yaxis_title="f(x)", yaxis_range=[-20, 20])
    st.plotly_chart(fig9, use_container_width=True)
    st.metric("2/(x-3)", f"{f9(x9):.2f}")
    st.caption("Figura 15 del libro: la recta x = 3 es asintota vertical.")
    st.header("CALCULO DE LIMITES MEDIANTE LAS LEYES DE LOS LIMITES")
    st.write("En la seccion anterior usamos calculadoras y graficas para estimar los limites, y vimos que tales metodos no siempre producen la respuesta correcta. En esta seccion usaremos propiedades de los limites, que se llaman Leyes de los limites, para calcularlos.")
    st.write("Si c es una constante y existen los limites:")
    st.latex(r"\lim_{x \to a} f(x) \quad y \quad \lim_{x \to a} g(x)")
    st.write("Entonces:")
    st.latex(r"1. \ \lim_{x \to a} [f(x) + g(x)] = \lim_{x \to a} f(x) + \lim_{x \to a} g(x)")
    st.latex(r"2. \ \lim_{x \to a} [f(x) - g(x)] = \lim_{x \to a} f(x) - \lim_{x \to a} g(x)")
    st.latex(r"3. \ \lim_{x \to a} [c f(x)] = c \lim_{x \to a} f(x)")
    st.latex(r"4. \ \lim_{x \to a} [f(x) \cdot g(x)] = \lim_{x \to a} f(x) \cdot \lim_{x \to a} g(x)")
    st.latex(r"5. \ \lim_{x \to a} \frac{f(x)}{g(x)} = \frac{\lim_{x \to a} f(x)}{\lim_{x \to a} g(x)} \quad \text{si} \ \lim_{x \to a} g(x) \neq 0")
    st.write("1. El limite de una suma es igual a la suma de los limites.")
    st.write("2. El limite de una resta es igual a la diferencia de los limites.")
    st.write("3. El limite de una constante multiplicada por una funcion es igual a la constante multiplicada por el limite de la funcion.")
    st.write("4. El limite de un producto es igual al producto de los limites.")
    st.write("5. El limite de un cociente es igual al cociente de los limites, siempre y cuando el limite del denominador no sea 0.")
